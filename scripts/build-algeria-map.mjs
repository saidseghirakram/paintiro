/**
 * Converts the Algeria wilaya boundaries (GeoJSON) into a compact SVG map module:
 *   lib/algeria-map.ts  ->  ALGERIA_VIEWBOX + WILAYAS [{ code, name, d, cx, cy, box }]
 *
 *   node scripts/build-algeria-map.mjs [data/algeria-wilayas.geojson]
 *
 * Source: geoBoundaries DZA ADM1 (OpenStreetMap contributors, ODbL 1.0).
 * Coordinates are projected (equirectangular, scaled by cos(28°)) into a 1000-wide
 * viewBox, simplified and rounded so the whole map stays small.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const SOURCE = path.resolve(ROOT, process.argv[2] ?? "data/algeria-wilayas.geojson");
const OUTPUT = path.join(ROOT, "lib", "algeria-map.ts");
const WIDTH = 1000;
/** Points closer than this (viewBox units) to the previous kept point are dropped. */
const MIN_STEP = 0.9;

/** Official wilaya numbers and names (the 48 historical wilayas). */
const WILAYAS = [
  [1, "Adrar"], [2, "Chlef"], [3, "Laghouat"], [4, "Oum El Bouaghi"], [5, "Batna"], [6, "Béjaïa"],
  [7, "Biskra"], [8, "Béchar"], [9, "Blida"], [10, "Bouira"], [11, "Tamanrasset"], [12, "Tébessa"],
  [13, "Tlemcen"], [14, "Tiaret"], [15, "Tizi Ouzou"], [16, "Alger"], [17, "Djelfa"], [18, "Jijel"],
  [19, "Sétif"], [20, "Saïda"], [21, "Skikda"], [22, "Sidi Bel Abbès"], [23, "Annaba"], [24, "Guelma"],
  [25, "Constantine"], [26, "Médéa"], [27, "Mostaganem"], [28, "M'Sila"], [29, "Mascara"], [30, "Ouargla"],
  [31, "Oran"], [32, "El Bayadh"], [33, "Illizi"], [34, "Bordj Bou Arréridj"], [35, "Boumerdès"], [36, "El Tarf"],
  [37, "Tindouf"], [38, "Tissemsilt"], [39, "El Oued"], [40, "Khenchela"], [41, "Souk Ahras"], [42, "Tipaza"],
  [43, "Mila"], [44, "Aïn Defla"], [45, "Naâma"], [46, "Aïn Témouchent"], [47, "Ghardaïa"], [48, "Relizane"],
];

const normalize = (s) =>
  s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z]/g, "");
const ALIASES = { algiers: "alger" };
const byName = new Map(WILAYAS.map(([code, name]) => [normalize(name), { code, name }]));

async function main() {
  const geo = JSON.parse(await readFile(SOURCE, "utf8"));
  const rings = (geometry) =>
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;

  // Bounds in lon / lat.
  let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
  for (const f of geo.features) {
    for (const polygon of rings(f.geometry)) {
      for (const [lon, lat] of polygon[0]) {
        minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
        minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
      }
    }
  }
  const kx = Math.cos((28 * Math.PI) / 180);
  const scale = WIDTH / ((maxLon - minLon) * kx);
  const height = Math.round((maxLat - minLat) * scale);
  const project = ([lon, lat]) => [(lon - minLon) * kx * scale, (maxLat - lat) * scale];

  const out = [];
  for (const f of geo.features) {
    const key = normalize(f.properties.shapeName);
    const match = byName.get(ALIASES[key] ?? key);
    if (!match) throw new Error(`Unknown wilaya name: ${f.properties.shapeName}`);

    let d = "";
    let area = 0, cx = 0, cy = 0;
    let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
    for (const polygon of rings(f.geometry)) {
      polygon.forEach((ring, ringIndex) => {
        const pts = [];
        for (const coord of ring) {
          const p = project(coord);
          const last = pts[pts.length - 1];
          if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= MIN_STEP) pts.push(p);
        }
        if (pts.length < 3) return;
        d += "M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z";
        if (ringIndex !== 0) return;
        // Area-weighted centroid of the outer ring (for the pin position).
        for (let i = 0; i < pts.length; i++) {
          const [ax, ay] = pts[i];
          const [bx, by] = pts[(i + 1) % pts.length];
          const cross = ax * by - bx * ay;
          area += cross; cx += (ax + bx) * cross; cy += (ay + by) * cross;
          x0 = Math.min(x0, ax); y0 = Math.min(y0, ay); x1 = Math.max(x1, ax); y1 = Math.max(y1, ay);
        }
      });
    }
    out.push({
      code: match.code,
      name: match.name,
      d,
      cx: +(cx / (3 * area)).toFixed(1),
      cy: +(cy / (3 * area)).toFixed(1),
      box: [+x0.toFixed(1), +y0.toFixed(1), +(x1 - x0).toFixed(1), +(y1 - y0).toFixed(1)],
    });
  }
  out.sort((a, b) => a.code - b.code);

  const file = `/**
 * Algeria map: the 48 wilayas as SVG paths. GENERATED by scripts/build-algeria-map.mjs,
 * do not edit by hand. Boundaries: geoBoundaries / © OpenStreetMap contributors (ODbL 1.0).
 */

export type Wilaya = {
  /** Official wilaya number (1-48). */
  code: number;
  name: string;
  /** SVG path in the ALGERIA_VIEWBOX coordinate space. */
  d: string;
  /** Visual center, used for pins and labels. */
  cx: number;
  cy: number;
  /** Bounding box [x, y, width, height], used to zoom on the wilaya. */
  box: [number, number, number, number];
};

export const ALGERIA_VIEWBOX: [number, number, number, number] = [0, 0, ${WIDTH}, ${height}];

/** Approximate kilometres per viewBox unit (for "nearest distributor" distances). */
export const KM_PER_UNIT = ${(111.32 / scale).toFixed(4)};

export const WILAYAS: Wilaya[] = ${JSON.stringify(out)};
`;
  await writeFile(OUTPUT, file);
  const kb = Math.round(Buffer.byteLength(file) / 1024);
  console.log(`[map] lib/algeria-map.ts written: ${out.length} wilayas, viewBox 0 0 ${WIDTH} ${height}, ${kb} KB`);
}

main().catch((error) => {
  console.error("[map] failed:", error.message ?? error);
  process.exit(1);
});
